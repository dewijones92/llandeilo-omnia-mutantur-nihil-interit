// npm run textures [-- --force]: downloads each surface's photograph (pinned by checksum) and writes the colour
// and normal maps the landmark models use at each size (ADR 0055). The outputs are committed; the downloads stay
// in build/textures (ignored). A map on disk is kept unless --force, or unless its recorded inputs (the photograph, the
// surface's detail, the size, process.py) are no longer the ones in src/content/generated/textures.ts.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SURFACES } from '../../src/content/surfaces.ts';
import { TEXTURE_SIZE, TEXTURED } from '../../src/domain/surfaces.ts';
import { PROCESS, ROOT, textureInputHash, textureKey, type MapKind } from './inputs.ts';

const INDEX = join(ROOT, 'src/content/generated/textures.ts');
const RAW = join(ROOT, 'build/textures');
const force = process.argv.includes('--force');

async function download(url: string, md5: string, to: string): Promise<void> {
  if (existsSync(to) && createHash('md5').update(readFileSync(to)).digest('hex') === md5) return;
  const res = await fetch(url, { headers: { 'User-Agent': 'llandeilo-texture-build' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${String(res.status)}`);
  const bytes = new Uint8Array(await res.arrayBuffer());
  const got = createHash('md5').update(bytes).digest('hex');
  if (got !== md5)
    throw new Error(`${url}: md5 ${got}, expected ${md5}: the photograph changed at the library`);
  writeFileSync(to, bytes);
  console.log(`dewidebug textures downloaded ${url} bytes=${String(bytes.byteLength)}`);
}

mkdirSync(RAW, { recursive: true });
mkdirSync(join(ROOT, 'public/textures/landmarks'), { recursive: true });
const recorded = new Map<string, string>();
if (existsSync(INDEX))
  for (const m of readFileSync(INDEX, 'utf8').matchAll(/'([^']+)': '([0-9a-f]{16})'/g))
    if (m[1] && m[2]) recorded.set(m[1], m[2]);
const inputs: Record<string, string> = {};
let written = 0;
for (const id of TEXTURED) {
  const s = SURFACES[id];
  for (const map of ['color', 'normal'] as const satisfies readonly MapKind[]) {
    const raw = join(RAW, `${id}-${map}.jpg`);
    await download(s.photo[map].url, s.photo[map].md5, raw);
    for (const size of Object.values(TEXTURE_SIZE)) {
      const key = textureKey(id, map, size);
      const hash = textureInputHash(id, map, size);
      inputs[key] = hash;
      const out = join(ROOT, 'public', key);
      if (existsSync(out) && !force && recorded.get(key) === hash) continue;
      const args = [PROCESS, raw, out, String(size), map];
      execFileSync('python3', ['-I', ...args, ...(map === 'color' ? [String(s.look.detail)] : [])], {
        stdio: ['ignore', 'inherit', 'inherit'],
      });
      written++;
    }
  }
}
console.log(`dewidebug textures wrote ${String(written)} files`);

const lines = Object.entries(inputs).map(([k, v]) => `  '${k}': '${v}',`);
writeFileSync(
  INDEX,
  `// Generated by tools/textures/build.ts (npm run textures): do not edit.\n// What each committed texture was made from, so a changed setting cannot leave an old map behind.\n\nexport const TEXTURE_INPUTS: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`dewidebug textures index lists ${String(lines.length)} maps`);
