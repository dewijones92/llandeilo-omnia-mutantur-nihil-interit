// npm run downloads: makes the models the app offers for download ready (ADR 0058).
//  1. stamps the credit and licence from src/content/assets.ts into every model glb's asset block and first scene's extras
//     (the landmark models, with where each stands on the terrain, and the train);
//  2. writes src/content/generated/downloads.ts (each landmark's part tiers, the train's size), and refreshes the models index.
// The terrain tiles are not made here: they are release assets (npm run terrain-glb -- <outdir>).
// Run it after `npm run models` or after rebuilding the train.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { assetFor } from '../../src/content/assets.ts';
import { glbCounts, readGlb, writeGlb, type Glb } from '../models/glb.ts';
import { groundHeightAt, loadLidar } from '../terrain/export-glb.ts';
import { anchorOf, isStamped, modelPlacement, partTiers, stampAsset } from './stamp.ts';

const ROOT = join(import.meta.dirname, '../..');
const PUBLIC = join(ROOT, 'public');
const TRAIN = 'models/llanelly-train.glb';
const LANDMARKS = 'models/landmarks';
const INDEX = join(ROOT, 'src/content/generated/downloads.ts');

const refreshModelsIndex = (): void => {
  execFileSync(process.execPath, ['tools/models/build.ts'], { cwd: ROOT, stdio: 'inherit' });
};

function stampFile(file: string, extra?: (glb: Glb) => Record<string, unknown>): void {
  const record = assetFor(file);
  if (!record) throw new Error(`assets.ts has no record for ${file}`);
  const path = join(PUBLIC, file);
  const glb = readGlb(readFileSync(path));
  const more = extra?.(glb);
  if (isStamped(glb, record, more)) {
    console.log(`dewidebug downloads ${file} already carries its credit and licence`);
    return;
  }
  writeFileSync(path, writeGlb(stampAsset(glb, record, more)));
  console.log(`dewidebug downloads stamped the credit and licence into ${file}`);
}

refreshModelsIndex();
const lidar = loadLidar();
const { sceneOrigin } = lidar.manifest;
const landmarkFiles = readdirSync(join(PUBLIC, LANDMARKS))
  .filter((f) => f.endsWith('.glb'))
  .map((f) => `${LANDMARKS}/${f}`);
for (const file of landmarkFiles)
  stampFile(file, (glb) => {
    const anchor = anchorOf(glb);
    const ground = groundHeightAt(lidar.manifest, lidar.data, anchor.e, anchor.n);
    console.log(
      `dewidebug downloads ${file} anchor E ${String(anchor.e)} N ${String(anchor.n)} stands at ${String(ground)}m`,
    );
    return { placement: modelPlacement(glb, sceneOrigin, ground) };
  });
stampFile(TRAIN);
const landmarkTiers: Record<string, ReturnType<typeof partTiers>> = {};
for (const file of landmarkFiles) {
  const tiers = partTiers(readGlb(readFileSync(join(PUBLIC, file))));
  if (tiers.documented + tiers.reconstructed + tiers.imagined > 0) landmarkTiers[file] = tiers;
}

const trainBytes = readFileSync(join(PUBLIC, TRAIN));
const train = {
  file: TRAIN,
  bytes: trainBytes.byteLength,
  triangles: glbCounts(readGlb(trainBytes).json).triangles,
};
writeFileSync(
  INDEX,
  `// Generated by tools/downloads/build.ts (npm run downloads): do not edit.\nimport type { ModelFile, PartTiers } from '../downloads.ts';\n\nexport const LANDMARK_TIERS: Readonly<Record<string, PartTiers>> = ${JSON.stringify(landmarkTiers, null, 2)};\n\nexport const TRAIN_MODEL: ModelFile = ${JSON.stringify(train, null, 2)};\n`,
);
refreshModelsIndex();
console.log(
  `dewidebug downloads index lists the train and ${String(Object.keys(landmarkTiers).length)} landmark models`,
);
