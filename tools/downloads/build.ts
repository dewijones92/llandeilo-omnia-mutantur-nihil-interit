// npm run downloads: makes everything the app offers for download ready (ADR 0058).
//  1. exports the detailed LiDAR tiles to public/models/terrain/*.glb (tools/terrain/export-glb.ts);
//  2. stamps the credit and licence from src/content/assets.ts into every glb's asset block (the landmark models, the train, the terrain);
//  3. writes src/content/generated/downloads.ts, the sizes the Downloads list shows, and refreshes the models index (which holds the landmark sizes).
// Run it after `npm run models`, after rebuilding the train, or after rebuilding the LiDAR tiles.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { assetFor } from '../../src/content/assets.ts';
import { exportTerrain, TERRAIN_DIR } from '../terrain/export-glb.ts';
import { glbCounts, readGlb, writeGlb } from '../models/glb.ts';
import { isStamped, stampAsset } from './stamp.ts';

const ROOT = join(import.meta.dirname, '../..');
const PUBLIC = join(ROOT, 'public');
const TRAIN = 'models/llanelly-train.glb';
const LANDMARKS = 'models/landmarks';
const INDEX = join(ROOT, 'src/content/generated/downloads.ts');

const refreshModelsIndex = (): void => {
  execFileSync(process.execPath, ['tools/models/build.ts'], { cwd: ROOT, stdio: 'inherit' });
};

function stampFile(file: string): void {
  const record = assetFor(file);
  if (!record) throw new Error(`assets.ts has no record for ${file}`);
  const path = join(PUBLIC, file);
  const glb = readGlb(readFileSync(path));
  if (isStamped(glb, record)) {
    console.log(`dewidebug downloads ${file} already carries its credit and licence`);
    return;
  }
  writeFileSync(path, writeGlb(stampAsset(glb, record)));
  console.log(`dewidebug downloads stamped the credit and licence into ${file}`);
}

refreshModelsIndex();
const terrain = exportTerrain(PUBLIC);
const kept = new Set(terrain.map((t) => t.file.slice(TERRAIN_DIR.length + 1)));
for (const name of readdirSync(join(PUBLIC, TERRAIN_DIR)))
  if (!kept.has(name)) {
    rmSync(join(PUBLIC, TERRAIN_DIR, name));
    console.log(`dewidebug downloads removed ${TERRAIN_DIR}/${name}, which is no longer a detailed tile`);
  }
for (const name of readdirSync(join(PUBLIC, LANDMARKS)).filter((f) => f.endsWith('.glb')))
  stampFile(`${LANDMARKS}/${name}`);
stampFile(TRAIN);

const trainBytes = readFileSync(join(PUBLIC, TRAIN));
const train = {
  file: TRAIN,
  bytes: trainBytes.byteLength,
  triangles: glbCounts(readGlb(trainBytes).json).triangles,
};
const tiles = terrain.map((t) => ({
  file: t.file,
  bytes: t.bytes,
  triangles: t.triangles,
  e: t.e,
  n: t.n,
  size: t.size,
  step: t.step,
  areas: t.areas,
  minHeight: t.minHeight,
  maxHeight: t.maxHeight,
}));
writeFileSync(
  INDEX,
  `// Generated by tools/downloads/build.ts (npm run downloads): do not edit.\nimport type { ModelFile, TerrainTileFile } from '../downloads.ts';\n\nexport const TRAIN_MODEL: ModelFile = ${JSON.stringify(train, null, 2)};\n\nexport const TERRAIN_TILES: readonly TerrainTileFile[] = ${JSON.stringify(tiles, null, 2)};\n`,
);
refreshModelsIndex();
console.log(
  `dewidebug downloads index lists the train and ${String(tiles.length)} terrain tiles (${String(tiles.reduce((s, t) => s + t.bytes, 0))} bytes)`,
);
