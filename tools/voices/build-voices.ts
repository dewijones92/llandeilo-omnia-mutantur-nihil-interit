import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CONVERSATIONS } from '../../src/content/conversations.ts';
import { CUTSCENES } from '../../src/content/cutscenes.ts';
import { PEOPLE } from '../../src/content/people.ts';
import { narrationLines, voiceLines, voiceSignature } from '../../src/content/voices.ts';

const out = join(import.meta.dirname, '../../public/voices');
const manifestPath = join(out, 'manifest.json');

const previous: Record<string, string> = {};
if (existsSync(manifestPath)) {
  const raw: unknown = JSON.parse(readFileSync(manifestPath, 'utf8'));
  if (raw && typeof raw === 'object') {
    for (const [k, v] of Object.entries(raw)) if (typeof v === 'string') previous[k] = v;
  }
}
const manifest: Record<string, string> = {};
let made = 0;
let kept = 0;
const narration = narrationLines(CUTSCENES);
for (const line of [...voiceLines(CONVERSATIONS, PEOPLE), ...narration]) {
  const hash = createHash('sha1').update(voiceSignature(line)).digest('hex').slice(0, 12);
  const file = join(out, `${line.key}.mp3`);
  manifest[line.key] = hash;
  if (previous[line.key] === hash && existsSync(file)) {
    kept++;
    continue;
  }
  execFileSync(
    'edge-tts',
    [
      '--voice',
      line.voice,
      `--pitch=${line.pitch}`,
      `--rate=${line.rate}`,
      '--text',
      line.text,
      '--write-media',
      file,
    ],
    {
      stdio: 'inherit',
    },
  );
  made++;
  console.log(`dewidebug voice ${line.key} ${line.voice} ${line.pitch} ${line.rate}`);
}
let removed = 0;
for (const f of readdirSync(out)) {
  if (f.endsWith('.mp3') && !(f.slice(0, -4) in manifest)) {
    unlinkSync(join(out, f));
    removed++;
  }
}
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
// How long each narration clip runs, so a test can check every caption stays up while it is read.
const seconds: Record<string, number> = {};
for (const line of narration) {
  const probe = execFileSync('ffprobe', [
    '-v',
    'error',
    '-show_entries',
    'format=duration',
    '-of',
    'csv=p=0',
    join(out, `${line.key}.mp3`),
  ]);
  seconds[line.key] = Math.round(Number(probe.toString().trim()) * 100) / 100;
}
writeFileSync(
  join(import.meta.dirname, '../../src/content/generated/narration.ts'),
  `// Generated by tools/voices/build-voices.ts from the clips in public/voices. Do not edit by hand.\nexport const NARRATION_SECONDS: Readonly<Record<string, number>> = ${JSON.stringify(seconds, null, 2)};\n`,
);
console.log(`dewidebug voices made=${made} kept=${kept} removed=${removed}`);
