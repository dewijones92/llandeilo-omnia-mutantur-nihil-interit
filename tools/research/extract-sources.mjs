#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const root = new URL('../../', import.meta.url).pathname;
const dir = join(root, 'docs/research');
const PREFIX = {
  'timeline-and-earliest-occupation': 'timeline',
  'era-iron-age': 'ironage',
  'era-medieval-to-1282': 'medieval',
  'era-victorian': 'victorian',
  'language-by-class': 'language',
  'deep-time-and-natural-history': 'deeptime',
  'conversations-by-class': 'classes',
  'railway-locomotives': 'railway',
};

const entries = [];
for (const file of readdirSync(dir)
  .filter((f) => f.endsWith('.md'))
  .sort()) {
  const slug = basename(file, '.md');
  const prefix = PREFIX[slug] ?? slug;
  const text = readFileSync(join(dir, file), 'utf8');
  const start = text.search(/^## Sources\s*$/m);
  if (start < 0) {
    console.warn(`dewidebug extract-sources: no Sources section in ${file}`);
    continue;
  }
  const body = text.slice(start).split('\n').slice(1);
  let current = null;
  const flush = () => {
    if (!current) return;
    const joined = current.lines.join(' ').replace(/\s+/g, ' ').trim();
    const url = (joined.match(/https?:\/\/[^\s)>\]]+/) ?? [''])[0].replace(/[.,;]+$/, '');
    let title = joined.split(/https?:\/\//)[0] ?? joined;
    title = title
      .replace(/\*\*/g, '')
      .replace(/[—–-]\s*$/, '')
      .replace(/\s+/g, ' ')
      .trim();
    if (title.length > 220) title = `${title.slice(0, 217)}…`;
    entries.push({ id: `${prefix}:${current.id}`, title, url, doc: `docs/research/${file}` });
    current = null;
  };
  for (const line of body) {
    if (/^## /.test(line)) break;
    const m = line.match(/^\s*(?:-\s*)?(?:\*\*)?\[(S\d+[a-z]?)\](?:\*\*)?\s*(.*)$/);
    if (m) {
      flush();
      current = { id: m[1], lines: [m[2]] };
    } else if (current && line.trim()) {
      current.lines.push(line.trim());
    }
  }
  flush();
}

const out = `// Generated by tools/research/extract-sources.mjs from docs/research/*.md. Do not edit by hand.
export const SOURCE_SEEDS = ${JSON.stringify(entries, null, 2)} as const;
`;
writeFileSync(join(root, 'src/content/generated/sources.ts'), out);
console.log(
  `dewidebug extract-sources wrote ${entries.length} sources from ${new Set(entries.map((e) => e.doc)).size} docs`,
);
