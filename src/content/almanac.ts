const doc = (...k: [SourceKey, ...SourceKey[]]): Provenance => ({
  kind: 'documented',
  sources: [src(k[0]), ...k.slice(1).map(src)],
});
const rec = (en: string, cy: string, ...k: SourceKey[]): Provenance => ({
  kind: 'reconstructed',
  basis: { en, cy },
  sources: k.map(src),
});

